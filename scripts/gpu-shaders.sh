#!/bin/zsh
# Compiles every Packages/SQGPU/Shaders/*.slang module (except Bindings.slang) to MSL (one source per module) and HLSL
# (one source per entry, compute, vertex or fragment: slangc writes one module per -entry) and writes them as Swift string literals to
# Packages/SQGPU/Sources/SQGPUKernels/Generated/ShaderSources.swift, which is checked in (the PC and the Mac build need no
# Slang). Run after editing a .slang file. Slang: ~/tools/slang/bin/slangc (or SQ_SLANGC), Apache-2.0.
set -eu
cd "$(dirname "$0")/../Packages/SQGPU/Shaders"
S=${SQ_SLANGC:-$HOME/tools/slang/bin/slangc}
tmp=$(mktemp -d "${TMPDIR:-/tmp}/sqgpu-slang.XXXX")
trap 'rm -rf "$tmp"' EXIT
out=../Sources/SQGPUKernels/Generated/ShaderSources.swift
strip() { grep -v '^#line' "$1" | grep -v '^[[:space:]]*$'; }
{
  echo "// Generated by scripts/gpu-shaders.sh from Packages/SQGPU/Shaders/*.slang ($($S -version 2>&1 | head -1)). Do not edit."
  echo "// swiftlint:disable all"
  echo "import SQGPU"
  echo
  echo "public enum GeneratedShaders {"
  mods=()
  for f in *.slang; do
    [[ $f == Bindings.slang ]] && continue
    m=${f%.slang}
    lower="${(L)m[1]}${m[2,-1]}"
    mods+=($lower)
    $S $f -warnings-disable 39029,39001 -target metal -D SQ_METAL -o $tmp/$m.metal
    parts=($f $(grep -oE '#include "Parts/[A-Za-z0-9_]+\.slang"' $f | sed -E 's/#include "(.*)"/\1/'))
    pairs=($(grep -h -A1 'shader("\(compute\|vertex\|fragment\)")' $parts | awk '
      match($0, /shader\("[a-z]+"\)/) { st = substr($0, RSTART + 8, RLENGTH - 10); next }
      st != "" && match($0, /^[A-Za-z0-9_]+ [A-Za-z0-9_]+\(/) { split(substr($0, RSTART, RLENGTH - 1), w, " "); print st ":" w[2]; st = "" }'))
    entries=(${pairs#*:})
    stages=$(for p in $pairs; do [[ ${p%%:*} == compute ]] || printf '"%s": .%s, ' ${p#*:} ${p%%:*}; done | sed 's/, $//')
    echo "    public static let $lower = GPUShaderModule(name: \"$m\", entries: [$(printf '"%s", ' $entries | sed 's/, $//')],"
    [[ -n $stages ]] && echo "        stages: [$stages],"
    echo "        msl: #\"\"\""
    strip $tmp/$m.metal
    echo "\"\"\"#,"
    echo "        hlsl: ["
    for e in $entries; do
      $S $f -warnings-disable 39029,39001 -target hlsl -entry $e -o $tmp/$m.$e.hlsl
      echo "            \"$e\": #\"\"\""
      strip $tmp/$m.$e.hlsl
      echo "\"\"\"#,"
    done
    echo "        ])"
  done
  echo "    /// Every module, for checks that walk all entries."
  echo "    public static let all: [GPUShaderModule] = [$(printf '%s, ' $mods | sed 's/, $//')]"
  echo "}"
} > $tmp/out.swift
mv $tmp/out.swift $out
echo "slang ok: $(grep -c 'GPUShaderModule(' $out) modules -> $out"
