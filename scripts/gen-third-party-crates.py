#!/usr/bin/env python3
"""Writes docs/THIRD_PARTY-CRATES.md: every Rust crate that ends up in the `sequence-studio` binary.

Input is `cargo metadata --format-version 1 --locked` (file argument or stdin), so no cargo plugin is needed:
    cargo metadata --format-version 1 --locked > meta.json && scripts/gen-third-party-crates.py meta.json
The list follows normal (non-dev, non-build) dependencies from the binary over all target platforms, so it is a
superset of what one platform links. License strings are SPDX expressions from each crate's Cargo.toml.
Exits 1 when a crate has no license field or none of its alternatives is GPL-3.0-or-later compatible.
"""
import json, re, sys

OK = {"MIT", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "ISC", "Zlib", "Unicode-3.0", "Unicode-DFS-2016", "CC0-1.0",
      "MPL-2.0", "BSL-1.0", "0BSD", "LGPL-2.1", "LGPL-2.1-or-later", "LGPL-3.0", "LGPL-3.0-or-later", "GPL-3.0",
      "GPL-3.0-or-later", "GPL-3.0-only", "IJG", "OFL-1.1", "Unlicense", "NCSA", "CDLA-Permissive-2.0", "MIT-0",
      "Apache-2.0 WITH LLVM-exception", "LGPL-2.0", "LGPL-2.0-or-later"}

# Git dependencies whose Cargo.toml has no license field: the LICENSE file of the pinned revision was read (docs/THIRD_PARTY.md).
READ = {"gyroflow-core": "GPL-3.0", "stabilize_spirv": "GPL-3.0", "rs-sync": "LGPL-2.1"}


def compatible(expr):
    # An OR expression is usable when one alternative is; an AND needs all.
    expr = expr.replace("/", " OR ").replace("(", " ").replace(")", " ")
    for alt in re.split(r"\s+OR\s+", expr):
        parts = [p.strip() for p in re.split(r"\s+AND\s+", alt) if p.strip()]
        if parts and all(p in OK for p in parts):
            return True
    return False


def main():
    meta = json.load(open(sys.argv[1]) if len(sys.argv) > 1 else sys.stdin)
    pk = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = next(i for i, p in pk.items() if p["name"] == "sequence-studio")
    seen, todo = set(), [root]
    while todo:
        i = todo.pop()
        if i in seen:
            continue
        seen.add(i)
        for d in nodes[i]["deps"]:
            if any(k["kind"] is None for k in d["dep_kinds"]):
                todo.append(d["pkg"])
    rows, bad = [], []
    for i in sorted(seen, key=lambda i: (pk[i]["name"], pk[i]["version"])):
        p = pk[i]
        if p["source"] is None:  # workspace member: our own code
            continue
        lic = p.get("license") or READ.get(p["name"]) or ("see " + p["license_file"] if p.get("license_file") else "")
        if not lic or not compatible(lic):
            bad.append(f'{p["name"]} {p["version"]}: {lic or "no license"}')
        rows.append((p["name"], p["version"], lic or "MISSING", p.get("repository") or "https://crates.io/crates/" + p["name"]))
    out = ["# Rust crates in the binary", "",
           "Generated by `scripts/gen-third-party-crates.py` from `cargo metadata` (Cargo.lock). Do not edit by hand: regenerate after a",
           "dependency change. Normal dependencies of `sequence-studio` over all target platforms, so one platform links a subset.",
           "Libraries that are not crates (FFmpeg, ONNX Runtime, fonts, models) are listed in `docs/THIRD_PARTY.md`.", "",
           f"{len(rows)} crates.", "", "| Crate | Version | License | Source |", "|---|---|---|---|"]
    out += [f"| {n} | {v} | {l} | {r} |" for n, v, l, r in rows]
    open("docs/THIRD_PARTY-CRATES.md", "w").write("\n".join(out) + "\n")
    print(f"{len(rows)} crates written to docs/THIRD_PARTY-CRATES.md")
    for b in bad:
        print("CHECK:", b)
    sys.exit(1 if bad else 0)


main()
