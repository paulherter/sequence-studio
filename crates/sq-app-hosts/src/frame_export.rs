    fn a_path_without_a_known_extension_becomes_a_png() {
        let d = dir("noext");
        assert_eq!(save_to(&d.join("frame"), &image(1.0)), "Exported frame.png");
        assert!(d.join("frame.png").exists());
        let _ = std::fs::remove_dir_all(d);
    }

    #[test]
    fn names_come_from_the_sequence_or_the_clip_without_its_extension() {
        assert_eq!(suggested_name("Sequence 01"), "Sequence 01.png");
        assert_eq!(suggested_name("clip.mov"), "clip.png");
        assert_eq!(suggested_name(""), "Frame.png");
    }

    #[test]
    fn png_jpeg_and_tiff_embed_the_icc_profile() {
        let d = dir("icc");
        let img = image(1.0);
        for name in ["t.png", "t.jpg", "t.tiff"] {
            assert_eq!(save_to(&d.join(name), &img), format!("Exported {name}"));
        }
        let r = png::Decoder::new(std::io::BufReader::new(std::fs::File::open(d.join("t.png")).expect("open")))
            .read_info()
            .expect("png");
        assert_eq!(r.info().icc_profile.as_deref(), Some(itu_709_icc()), "iCCP");
        assert!(r.info().coding_independent_code_points.is_some(), "cICP stays");

        let jpg = std::fs::read(d.join("t.jpg")).expect("jpg");
        let tag = b"ICC_PROFILE\0";
        let at = jpg.windows(tag.len()).position(|w| w == tag).expect("APP2 ICC_PROFILE");
        assert_eq!(&jpg[at - 4..at - 2], &[0xFF, 0xE2], "APP2 marker");
        assert_eq!(&jpg[at + 14..at + 14 + itu_709_icc().len()], itu_709_icc(), "one chunk, whole profile");

        let tif = d.join("t.tiff");
        let mut dec = tiff::decoder::Decoder::new(std::io::BufReader::new(std::fs::File::open(tif).expect("open")))
            .expect("tiff");
        assert_eq!(dec.get_tag_u8_vec(tiff::tags::Tag::IccProfile).expect("tag 34675"), itu_709_icc());

        let alpha = d.join("ta.tiff");
        assert_eq!(save_to(&alpha, &image(0.5)), "Exported ta.tiff");
        let mut dec = tiff::decoder::Decoder::new(std::io::BufReader::new(std::fs::File::open(alpha).expect("open")))
            .expect("tiff");
        assert_eq!(dec.get_tag_u8_vec(tiff::tags::Tag::IccProfile).expect("tag"), itu_709_icc());
        assert_eq!(dec.get_tag_u32_vec(tiff::tags::Tag::ExtraSamples).expect("extra samples"), vec![2]);
        let _ = std::fs::remove_dir_all(d);
    }
