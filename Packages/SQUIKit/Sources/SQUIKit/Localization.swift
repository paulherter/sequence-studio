import Foundation

/// UI string lookup. American English is the source language: the English text is the key, so an untranslated string
/// shows English (fallback) and code stays readable. Catalogs are `Resources/Localization/<lang>.lproj/Localizable.strings`.
/// The language follows the system preference list unless `sq.language` in UserDefaults holds a supported code.
/// Add a language: put a `<code>.lproj` folder next to `de.lproj` and append the code to `supported`.
public enum SQL10n {
    public static let defaultsKey = "sq.language"
    public static let sourceLanguage = "en"
    public static let supported = ["en", "de"]

    /// Language code to use. `override` is the `sq.language` value ("system", nil or unsupported means: follow `preferred`).
    public static func resolveLanguage(override: String?, preferred: [String]) -> String {
        if let o = override, o != "system" {
            return supported.contains(o) ? o : sourceLanguage
        }
        for tag in preferred {
            let code = String(tag.split(whereSeparator: { $0 == "-" || $0 == "_" }).first ?? "").lowercased()
            if supported.contains(code) { return code }
        }
        return sourceLanguage
    }

    /// The `sq.language` override to use: the environment variable `SQ_LANGUAGE` (a code or "system") beats the stored value
    /// only outside an app bundle (scripts/test.sh sets it to `en` so tests that compare English UI text pass on a German
    /// Mac). Inside the shipped .app an inherited environment variable must never force a language.
    public static func effectiveOverride(env: String?, stored: String?, isAppBundle: Bool) -> String? {
        if !isAppBundle, let env, !env.isEmpty { return env }
        return stored
    }

    /// The language the user has chosen right now (system preference list plus the `sq.language` override). Changes at
    /// once when the setting changes; the interface itself keeps `currentLanguage` until the next launch.
    public static var selectedLanguage: String {
        let env = ProcessInfo.processInfo.environment["SQ_LANGUAGE"]
        let override = effectiveOverride(env: env, stored: UserDefaults.standard.string(forKey: defaultsKey),
                                         isAppBundle: Bundle.main.bundleURL.pathExtension == "app")
        return resolveLanguage(override: override, preferred: Locale.preferredLanguages)
    }

    /// Language the interface was built in. Fixed for the whole run, so one window never mixes two languages.
    public static let launchLanguage: String = selectedLanguage

    /// Language in effect now: fixed at first use, a new choice applies at the next launch.
    public static var currentLanguage: String { launchLanguage }

    /// The chosen language differs from the one running: the app has to restart to show it.
    public static var restartPending: Bool { selectedLanguage != launchLanguage }

    /// Translated text, or `key` itself when the language is English or the key is missing.
    public static func string(_ key: String, language: String? = nil) -> String {
        let lang = language ?? currentLanguage
        if lang == sourceLanguage { return key }
        return table(for: lang)[key] ?? key
    }

    /// Translates a finished English message whose arguments are already filled in (an engine error text, a stored status
    /// line): the exact key first, then every `%@` key matched as a pattern; its captured arguments are translated the same
    /// way (a nested message). English or no match: the text itself. SQMedia/SQExport cannot import SQUIKit, so their
    /// errors carry English and the display sink calls this.
    public static func localized(_ text: String, language: String? = nil) -> String {
        let lang = language ?? currentLanguage
        if lang == sourceLanguage { return text }
        if let t = table(for: lang)[text] { return t }
        for entry in patterns(for: lang) {
            let ns = text as NSString
            guard let m = entry.regex.firstMatch(in: text, range: NSRange(location: 0, length: ns.length)),
                  m.numberOfRanges == entry.count + 1 else { continue }
            let args: [CVarArg] = (0..<entry.count).map {
                localized(ns.substring(with: m.range(at: $0 + 1)), language: lang) as CVarArg
            }
            return String(format: entry.translation, arguments: args)
        }
        return text
    }

    /// The message of `error` in the interface language (`localized` over its description).
    public static func errorText(_ error: Error, language: String? = nil) -> String {
        localized((error as? LocalizedError)?.errorDescription ?? error.localizedDescription, language: language)
    }

    private struct PatternEntry { var regex: NSRegularExpression; var translation: String; var count: Int }
    private final class PatternCache: @unchecked Sendable {
        let lock = NSLock()
        var byLanguage: [String: [PatternEntry]] = [:]
    }
    private static let patternCache = PatternCache()

    private static func patterns(for language: String) -> [PatternEntry] {
        patternCache.lock.lock(); defer { patternCache.lock.unlock() }
        if let p = patternCache.byLanguage[language] { return p }
        var out: [PatternEntry] = []
        for (key, value) in table(for: language) where key.contains("%@") {
            let parts = key.components(separatedBy: "%@")
            let pattern = "^" + parts.map { NSRegularExpression.escapedPattern(for: $0) }.joined(separator: "(.+?)") + "$"
            if let re = try? NSRegularExpression(pattern: pattern, options: [.dotMatchesLineSeparators]) {
                out.append(PatternEntry(regex: re, translation: value, count: parts.count - 1))
            }
        }
        // Longer literal text first: the most specific key wins.
        out.sort { $0.regex.pattern.count > $1.regex.pattern.count }
        patternCache.byLanguage[language] = out
        return out
    }

    /// `string(format)` with `%@` arguments substituted.
    public static func format(_ format: String, _ args: CVarArg..., language: String? = nil) -> String {
        String(format: string(format, language: language), arguments: args)
    }

    private final class Cache: @unchecked Sendable {
        let lock = NSLock()
        var tables: [String: [String: String]] = [:]
    }
    private static let cache = Cache()

    /// Key to translation of one language (empty for English and unknown codes).
    public static func table(for language: String) -> [String: String] {
        cache.lock.lock(); defer { cache.lock.unlock() }
        if let t = cache.tables[language] { return t }
        var t: [String: String] = [:]
        if let url = Bundle.module.url(forResource: "Localizable", withExtension: "strings",
                                       subdirectory: "Localization/\(language).lproj"),
           let dict = NSDictionary(contentsOf: url) as? [String: String] {
            t = dict
        }
        cache.tables[language] = t
        return t
    }

    /// Keys of `required` that have no non-empty translation in `language`.
    public static func missingKeys(in language: String, required: [String]) -> [String] {
        let t = table(for: language)
        return required.filter { (t[$0] ?? "").isEmpty }
    }

    /// The strings every supported language must translate (first vertical slice): menu and submenu titles, panel names,
    /// every menu command, app/Help/Settings chrome. The localization test fails when one is missing.
    public static var requiredKeys: [String] {
        var keys: [String] = []
        func walk(_ items: [MenuSpec.Item]) {
            for item in items { if case .submenu(let title, let sub) = item { keys.append(title); walk(sub) } }
        }
        for spec in EditorMenus.all {
            keys.append(spec.title)
            walk(spec.items)
        }
        for command in EditorMenus.all.flatMap(\.commands) { keys.append(command.title) }
        keys += PanelID.allCases.map { EditorCommand.panelTitle($0) }
        keys += chromeKeys
        keys += settingsKeys
        keys += dialogKeys
        keys += appMenuKeys
        keys += undoPatterns + undoNames + sessionUndoNames + statusKeys + countKeys + SQAccessibilityText.keys
        var seen = Set<String>()
        return keys.filter { !$0.isEmpty && seen.insert($0).inserted }
    }

